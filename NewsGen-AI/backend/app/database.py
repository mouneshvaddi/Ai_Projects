
import os
import hashlib
import re

from datetime import datetime, timezone
from urllib.parse import urlsplit, urlunsplit, parse_qsl, urlencode

import psycopg
from psycopg.rows import dict_row

# PostgreSQL connection
DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL environment variable is missing.")

def get_connection():
    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row
    )

# Normalize article URL
def normalize_url(url):
    parts = urlsplit(url.strip())

    query_params = [
        (key, value)
        for key, value in parse_qsl(parts.query)
        if not key.lower().startswith("utm_")
        and key.lower() not in ["fbclid", "gclid"]
    ]

    return urlunsplit((
        parts.scheme.lower(),
        parts.netloc.lower(),
        parts.path.rstrip("/"),
        urlencode(query_params),
        ""
    ))

def generate_article_hash(url):
    normalized_url = normalize_url(url)

    return hashlib.sha256(
        normalized_url.encode("utf-8")
    ).hexdigest()

# Initialize PostgreSQL tables
def initialize_database():
    with get_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS articles (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                description TEXT,
                url TEXT NOT NULL,
                url_hash TEXT NOT NULL UNIQUE,
                source TEXT,
                published TEXT,
                status TEXT DEFAULT 'pending',
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS summaries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                article_id BIGINT NOT NULL UNIQUE
                    REFERENCES articles(id) ON DELETE CASCADE,
                headline TEXT,
                category TEXT,
                summary_text TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS processing_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                started_at TIMESTAMPTZ NOT NULL,
                completed_at TIMESTAMPTZ,
                fetched_count INTEGER DEFAULT 0,
                new_articles INTEGER DEFAULT 0,
                duplicate_count INTEGER DEFAULT 0,
                summarized_count INTEGER DEFAULT 0,
                failed_count INTEGER DEFAULT 0,
                status TEXT DEFAULT 'running'
            );
        """)

    print("PostgreSQL database initialized successfully!")

# Start processing history
def start_processing_run():
    with get_connection() as connection:
        cursor = connection.execute(
            """
            INSERT INTO processing_history (started_at)
            VALUES (%s)
            RETURNING id
            """,
            (datetime.now(timezone.utc),)
        )

        return cursor.fetchone()["id"]

# Save new article
def save_article(article):
    article_hash = generate_article_hash(article["link"])

    with get_connection() as connection:
        cursor = connection.execute(
            """
            INSERT INTO articles (
                title, description, url,
                url_hash, source, published, status
            )
            VALUES (%s, %s, %s, %s, %s, %s, 'pending')
            ON CONFLICT (url_hash) DO NOTHING
            RETURNING id
            """,
            (
                article["title"],
                article.get("description", ""),
                article["link"],
                article_hash,
                article.get("source", ""),
                article.get("published", "")
            )
        )

        row = cursor.fetchone()
        return row["id"] if row else None

# Get pending articles
def get_pending_articles():
    with get_connection() as connection:
        results = connection.execute(
            """
            SELECT *
            FROM articles
            WHERE status = 'pending'
            ORDER BY id ASC
            """
        ).fetchall()

        return [dict(row) for row in results]

# Save AI summary
def save_summary(article_id, summary_text):
    headline_match = re.search(
        r"HEADLINE:\s*(.*)",
        summary_text,
        re.IGNORECASE
    )

    category_match = re.search(
        r"CATEGORY:\s*(.*)",
        summary_text,
        re.IGNORECASE
    )

    headline = (
        headline_match.group(1).strip()
        if headline_match else ""
    )

    category = (
        category_match.group(1).strip()
        if category_match else "Other"
    )

    with get_connection() as connection:
        connection.execute(
            """
            INSERT INTO summaries (
                article_id, headline, category, summary_text
            )
            VALUES (%s, %s, %s, %s)
            ON CONFLICT (article_id) DO UPDATE SET
                headline = EXCLUDED.headline,
                category = EXCLUDED.category,
                summary_text = EXCLUDED.summary_text
            """,
            (article_id, headline, category, summary_text)
        )

        connection.execute(
            """
            UPDATE articles
            SET status = 'completed'
            WHERE id = %s
            """,
            (article_id,)
        )

# Update article status
def update_article_status(article_id, status):
    with get_connection() as connection:
        connection.execute(
            """
            UPDATE articles
            SET status = %s
            WHERE id = %s
            """,
            (status, article_id)
        )

# Complete processing history
def complete_processing_run(
    run_id,
    fetched,
    new_articles,
    duplicates,
    summarized,
    failed
):
    with get_connection() as connection:
        connection.execute(
            """
            UPDATE processing_history
            SET completed_at = %s,
                fetched_count = %s,
                new_articles = %s,
                duplicate_count = %s,
                summarized_count = %s,
                failed_count = %s,
                status = 'completed'
            WHERE id = %s
            """,
            (
                datetime.now(timezone.utc),
                fetched,
                new_articles,
                duplicates,
                summarized,
                failed,
                run_id
            )
        )

# Database statistics
def show_database_statistics():
    with get_connection() as connection:
        total = connection.execute(
            "SELECT COUNT(*) FROM articles"
        ).fetchone()["count"]

        summaries = connection.execute(
            "SELECT COUNT(*) FROM summaries"
        ).fetchone()["count"]

        pending = connection.execute(
            "SELECT COUNT(*) FROM articles WHERE status = 'pending'"
        ).fetchone()["count"]

        failed = connection.execute(
            "SELECT COUNT(*) FROM articles WHERE status = 'failed'"
        ).fetchone()["count"]

    print("\nDATABASE STATISTICS")
    print("-" * 40)
    print(f"Total articles: {total}")
    print(f"Total summaries: {summaries}")
    print(f"Pending articles: {pending}")
    print(f"Failed articles: {failed}")